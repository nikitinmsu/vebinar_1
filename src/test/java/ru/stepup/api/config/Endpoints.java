package ru.stepup.api.config;

/**
 * =====================================================================
 *  Endpoints — ЕДИНАЯ точка правды для всех URL и путей REST API
 * =====================================================================
 *
 *  Почему нужен отдельный класс:
 *  ------------------------------------------------
 *  URL и эндпоинты встречаются в запросах много раз (и в Page Object,
 *  и в билдере, и в тестах). Если писать строки напрямую в каждом
 *  месте — рано или поздно они разъедутся: где-то забудется «/»,
 *  где-то изменится версия API, и тесты начнут падать с непонятными
 *  ошибками. Поэтому ВСЕ адреса собраны здесь, в одном классе:
 *
 *    1. Меняется адрес — правим в ОДНОМ месте.
 *    2. Пути компилируются, опечатки ловятся на этапе сборки.
 *    3. Видно сразу, с каким сервисом работает тестовая обвязка.
 *
 *  Идея та же, что и у Page Object для UI: спрятать детали реализации
 *  (конкретные строки URL) за понятными именами констант/методов.
 *
 *  Класс объявлен как `final` с приватным конструктором — это
 *  «утилитный» класс, он не создаётся и не наследуется, он лишь
 *  хранит константы. Такой класс ещё называют *helper*.
 */
public final class Endpoints {

    // =================================================================
    //  БАЗОВЫЙ URL СЕРВИСА
    // =================================================================
    // Схема + хост + порт. Это «корень», к которому прибавляются пути
    // из секции ниже. Базовый адрес можно переопределить системным
    // свойством -Dapi.base.uri=... (см. ApiConfig).
    private static final String BASE_URI =
            System.getProperty("api.base.uri", "http://127.0.0.1");
    private static final int PORT =
            Integer.parseInt(System.getProperty("api.port", "8080"));

    // =================================================================
    //  ПУТИ (паттерны) — без хост/порта, только «хвост» URL
    // =================================================================
    // Ручки сервиса «Товары» (см. Swagger: /swagger-ui/index.html).
    // Префикс «/api/v1» можно было бы держать здесь же отдельной
    // константой и подставлять во все пути — удобно при смене версии.
    private static final String GOODS = "/goods";

    /** POST /goods/add — добавить новый товар (без параметров пути). */
    public static final String GOODS_ADD = GOODS + "/add";

    /** GET /goods/list — список товаров с пагинацией (параметры page/size). */
    public static final String GOODS_LIST = GOODS + "/list";

    /**
     * GET/PATCH/DELETE /goods/{id} — работа с товаром по идентификатору.
     * Переменная часть пути (id) подставляется методом {@link #goodsById(long)}.
     */
    private static final String GOODS_BY_ID = GOODS + "/{id}";

    // =================================================================
    //  МЕТОДЫ-СБОРЩИКИ ПОЛНОГО URL
    // =================================================================
    // Константы удобны для статичных путей, но когда в URL нужно
    // подставить значение (id, page, size) — чище сделать методы.
    // Такой подход повторяет паттерн Page Object: тест вызывает
    // понятный метод, а не лепит строку руками.

    /**
     * Полный URL для товара с конкретным идентификатором.
     *
     * @param id идентификатор товара
     * @return строка вида {@code http://127.0.0.1:8080/goods/42}
     */
    public static String goodsById(long id) {
        return BASE_URL + GOODS_BY_ID.replace("{id}", String.valueOf(id));
    }

    /**
     * Полный URL списка товаров с параметрами пагинации.
     *
     * @param page номер страницы (начиная с 0)
     * @param size размер страницы
     * @return строка вида {@code http://127.0.0.1:8080/goods/list?page=0&size=10}
     */
    public static String goodsList(int page, int size) {
        return BASE_URL + GOODS_LIST + "?page=" + page + "&size=" + size;
    }

    /**
     * Базовый URL сервиса — используется для конфигурации RestAssured.
     *
     * @return строка вида {@code http://127.0.0.1:8080}
     */
    public static String getBaseUrl() {
        return BASE_URL;
    }

    /**
     * Только схема + хост, без порта.
     * Нужен для RestAssured, который принимает baseUri и port раздельно.
     *
     * @return строка вида {@code http://127.0.0.1}
     */
    public static String getBaseUri() {
        return BASE_URI;
    }

    /**
     * Номер порта сервиса.
     *
     * @return целое число порта (по умолчанию 8080)
     */
    public static int getPort() {
        return PORT;
    }

    // Полный адрес «корня» сервиса: baseUri + порт.
    private static final String BASE_URL = BASE_URI + ":" + PORT;

    /**
     * Приватный конструктор — запрещаем создание экземпляров.
     * Класс утилитный: обращаемся только через статику.
     */
    private Endpoints() {
        throw new AssertionError("Утилитный класс не инстанцируется");
    }
}
